// RenderPlanExport formats a plan as dd-test-plan/1 Markdown.
// It is pure: now is the export clock, and nothing is read from the process environment.
func RenderPlanExport(plan store.TestPlan, accounts []store.TestAccount, now time.Time) string {
	lines := []string{
		"---",
		"format: dd-test-plan/1",
		"plan_id: " + plan.ID,
		"plan_key: " + plan.Key,
		"plan_version: " + strconv.Itoa(plan.Version),
		"app_id: " + plan.AppID,
		"archived: " + strconv.FormatBool(plan.Archived),
		"exported_at: " + now.UTC().Truncate(time.Second).Format(time.RFC3339),
		"---",
		"",
		"# Test plan: " + planTitle(plan),
		"",
		"Exported from Defect Drainer. Carry out every step in order and write the results as the",
		"Output contract describes. Do not edit this file.",
		"",
	}
	if !blankText(plan.Purpose) {
		lines = append(lines, "## Purpose", "")
		lines = append(lines, quoteBlock(plan.Purpose)...)
		lines = append(lines, "")
	}
	lines = append(lines, "## Environment", "")
	lines = append(lines, envLines(plan.Env)...)
	lines = append(lines, "", "## Account", "")
	lines = append(lines, accountLines(plan.Env, accounts)...)
	lines = append(lines, "", "## Steps", "")
	lines = append(lines, stepLines(plan.Steps)...)
	lines = append(lines, "", outputContract(plan))
	return strings.Join(lines, "\n") + "\n"
}

func planTitle(plan store.TestPlan) string {
	title := collapseWS(plan.Title)
	if title == "" {
		return plan.Key
	}
	return title
}

func blankText(s string) bool {
	return strings.TrimSpace(normalizeNewlines(s)) == ""
}

// isLineBreak reports a line break in Python's str.splitlines set:
// \n, \r, \r\n, U+000B, U+000C, U+001C, U+001D, U+001E, U+0085, U+2028, U+2029.
func isLineBreak(r rune) bool {
	switch r {
	case '\n', '\r', '\v', '\f', '\u0085', '\u2028', '\u2029', '\u001c', '\u001d', '\u001e':
		return true
	default:
		return false
	}
}

func normalizeNewlines(s string) string {
	var b strings.Builder
	b.Grow(len(s))
	runes := []rune(s)
	for i := 0; i < len(runes); i++ {
		r := runes[i]
		if r == '\r' && i+1 < len(runes) && runes[i+1] == '\n' {
			b.WriteByte('\n')
			i++
			continue
		}
		if isLineBreak(r) {
			b.WriteByte('\n')
			continue
		}
		b.WriteRune(r)
	}
	return b.String()
}

func collapseWS(s string) string {
	return strings.Join(strings.FieldsFunc(s, func(r rune) bool {
		return unicode.IsSpace(r) || isLineBreak(r)
	}), " ")
}

func quoteBlock(s string) []string {
	parts := strings.Split(normalizeNewlines(s), "\n")
	out := make([]string, len(parts))
	for i, line := range parts {
		if line == "" {
			out[i] = ">"
		} else {
			out[i] = "> " + line
		}
	}
	return out
}

func envLines(env map[string]any) []string {
	type pair struct {
		show string
		raw  string
	}
	var pairs []pair
	for k := range env {
		show := collapseWS(k)
		if show == "account" || show == "account_label" || show == "secret_ref" {
			continue
		}
		pairs = append(pairs, pair{show: show, raw: k})
	}
	sort.Slice(pairs, func(i, j int) bool {
		if pairs[i].show != pairs[j].show {
			return pairs[i].show < pairs[j].show
		}
		return pairs[i].raw < pairs[j].raw
	})
	if len(pairs) == 0 {
		return []string{"- (none)"}
	}
	out := make([]string, len(pairs))
	for i, p := range pairs {
		out[i] = "- " + p.show + ": " + envValue(env[p.raw])
	}
	return out
}

func envValue(v any) string {
	if s, ok := v.(string); ok {
		return collapseWS(s)
	}
	b, err := json.Marshal(stripSecretRef(v))
	if err != nil {
		return "null"
	}
	return string(b)
}

func accountLines(env map[string]any, accounts []store.TestAccount) []string {
	label, ok := accountLabel(env)
	if !ok {
		return []string{"- No test account; mark steps that need one blocked."}
	}
	acc, found := matchTestAccount(accounts, label)
	if !found {
		return []string{"- Account `" + collapseWS(label) + "` is not in this app's Settings; mark steps that need it `blocked`."}
	}
	lines := []string{"- Label: " + collapseWS(acc.Label), "- Username: " + collapseWS(acc.Username)}
	if environment := collapseWS(acc.Environment); environment != "" {
		lines = append(lines, "- Environment: "+environment)
	}
	return append(lines, passwordLines(acc.SecretRef)...)
}

func accountLabel(env map[string]any) (string, bool) {
	if env == nil {
		return "", false
	}
	s, ok := env["account_label"].(string)
	if !ok {
		return "", false
	}
	s = strings.TrimSpace(s)
	if s == "" {
		return "", false
	}
	return s, true
}

// matchTestAccount follows store.findTestAccount: trim the requested label,
// then compare case-insensitively to the stored label.
func matchTestAccount(accounts []store.TestAccount, label string) (store.TestAccount, bool) {
	want := strings.TrimSpace(label)
	for _, a := range accounts {
		if strings.EqualFold(a.Label, want) {
			return a, true
		}
	}
	return store.TestAccount{}, false
}

func passwordLines(ref string) []string {
	if name, ok := store.EnvSecretName(ref); ok {
		return []string{
			"- Password: read it from `$" + name + "`. It is not in this file. Never type, echo, log or",
			"  screenshot it. If the variable is unset, mark the steps that need it `blocked`.",
		}
	}
	if where := collapseWS(ref); where != "" {
		return []string{"- Password location: " + where + " (ask the operator). It is not in this file. Never type, echo, log or screenshot it."}
	}
	return []string{"- No password location is recorded; mark steps that need one blocked."}
}

func stepLines(steps []store.PlanStep) []string {
	if len(steps) == 0 {
		return []string{"- (no steps)"}
	}
	var out []string
	for i, s := range steps {
		if i > 0 {
			out = append(out, "")
		}
		heading := "### " + strconv.Itoa(s.Position) + ". `" + s.Key + "`"
		if section := collapseWS(s.Section); section != "" {
			heading += " — " + section
		}
		out = append(out, heading, "", "**Action**", "")
		out = append(out, quoteBlock(s.Action)...)
		out = append(out, "", "**Expected**", "")
		if blankText(s.Expected) {
			out = append(out, "> (not stated — record what you observe)")
		} else {
			out = append(out, quoteBlock(s.Expected)...)
		}
	}
	return out
}

func outputContract(plan store.TestPlan) string {
	ver := strconv.Itoa(plan.Version)
	return strings.Join([]string{
		"## Output contract",
		"",
		"Write everything into one output directory (default `./test-run-" + plan.Key + "-v" + ver + "/`):",
		"",
		"- `RUN.md`: a summary. Its first line is `PLAN: " + plan.ID + " v" + ver + "`. Then one",
		"  `COMMIT: <repo> <sha>` line per checkout you tested. Then one `NOT-RUN: <key> <reason>` line",
		"  per step you could not reach.",
		"- `results/<key>.md`: line 1 is exactly `STATUS: pass`, `STATUS: fail`, `STATUS: blocked` or",
		"  `STATUS: skipped`. The rest is what actually happened.",
		"- `results/x-<slug>.md`: a step that is not on the plan. Line 1 is `STATUS: …`, line 2 is",
		"  `ACTION: …`, line 3 may be `EXPECTED: …`, and the body follows.",
		"- `evidence/<key>/<file>`: one screenshot per step you checked, as " + screenshotExtList() + ". Take it during",
		"  this run and save it under a new name. Never overwrite a file.",
		"",
		"## Rules",
		"",
		"- A `pass` needs a screenshot taken during this run. `fail` and `blocked` need a note.",
		"- Do not edit product code to make a step pass. Do not commit, push or open PRs.",
		"- Never type, echo, log or screenshot the password.",
	}, "\n")
}

func screenshotExtList() string {
	exts := make([]string, 0, len(imageExts))
	for ext := range imageExts {
		exts = append(exts, ext)
	}
	sort.Strings(exts)
	for i, ext := range exts {
		exts[i] = strings.TrimPrefix(ext, ".")
	}
	return strings.Join(exts, ", ")
}
