package jobs

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/joe/defect-drainer-go/internal/git"
)

// Per-job grok sandbox profile (`<handoff>/.grok/sandbox.toml`).
//
// The built-in `workspace` profile reads everywhere but writes only to cwd,
// /tmp and ~/.grok — so `simctl install` (which writes into the CoreSimulator
// device tree) fails, and an agent can only produce widget renders instead of
// real on-device screenshots. grok supports custom profiles that extend a
// built-in one with extra `read_write` grants; DD writes one into the handoff
// so the grant is scoped to a single job and never edits the operator's global
// ~/.grok/sandbox.toml.
//
// Opt-in per app (App Settings → Simulator writes). Default off: this widens
// what a coding agent may modify on the host.
//
// The handoff is the agent's writable cwd, and grok re-resolves a profile by
// name from disk on every process start, `-c` and `-r` included (verified on
// 1.0.40). So the profile denies its own `.grok` dir — grok reads it before
// applying the sandbox, and the agent then cannot read, write, unlink or
// rename it — and DD re-checks the bytes before every iteration in case that
// ever stops holding.

func simulatorDevicesDir() string {
	home, err := os.UserHomeDir()
	if err != nil || home == "" {
		home = os.Getenv("HOME")
	}
	return filepath.Join(home, "Library", "Developer", "CoreSimulator", "Devices")
}

// SandboxProfileResult is the --sandbox name plus prompt notes. Body is the
// exact file written, for checkSimulatorSandboxProfile.
type SandboxProfileResult struct {
	Profile string
	Body    []byte
	Notes   []string
}

const simulatorProfileName = "dd-simulator"

// writeSimulatorSandboxProfile writes a job-scoped profile granting Simulator
// writes on top of base (`workspace` or `strict`). read_write takes literal
// directory grants (no globs). Never creates or edits ~/.grok/sandbox.toml.
//
// `.grok` is replaced, never written through: DD is unsandboxed, and an agent
// from an earlier run (or one without this profile) may have left a symlink
// there aimed at a host file.
func writeSimulatorSandboxProfile(handoffAbs, base, batchID string) (SandboxProfileResult, error) {
	if base != "workspace" {
		base = "strict"
	}
	devices := simulatorDevicesDir()
	dir := filepath.Join(handoffAbs, ".grok")
	extends, _ := json.Marshal(base)
	rw, _ := json.Marshal(devices)
	deny, _ := json.Marshal(dir)
	body := []byte(strings.Join([]string{
		"# Generated by Defect Drainer for " + batchID + " — job-scoped, not global.",
		"# Checked before every agent iteration: any change fails the job.",
		"[profiles." + simulatorProfileName + "]",
		"extends = " + string(extends),
		"read_write = [" + string(rw) + "]",
		"deny = [" + string(deny) + "]",
		"",
	}, "\n"))
	if err := os.RemoveAll(dir); err != nil {
		return SandboxProfileResult{}, err
	}
	if err := os.Mkdir(dir, 0o755); err != nil {
		return SandboxProfileResult{}, err
	}
	// O_EXCL also refuses a symlink planted between Mkdir and here.
	f, err := os.OpenFile(filepath.Join(dir, "sandbox.toml"), os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o644)
	if err != nil {
		return SandboxProfileResult{}, err
	}
	_, err = f.Write(body)
	if cerr := f.Close(); err == nil {
		err = cerr
	}
	if err != nil {
		return SandboxProfileResult{}, err
	}
	return SandboxProfileResult{
		Profile: simulatorProfileName,
		Body:    body,
		Notes: []string{
			"SIMULATOR: this job may write to the iOS Simulator device tree (" + devices + ").",
			"- Real app installs/launches are allowed: prefer simctl screenshots of the running app over widget-test renders.",
			"- Nothing else on the host became writable.",
		},
	}, nil
}

// checkSimulatorSandboxProfile runs before every agent iteration, Resume's
// first included. The job profile must be exactly what DD wrote, through no
// symlink; and the user-level sandbox.toml must not mention the profile name,
// because grok lets a user profile replace a project one wholesale — deny
// included. The name check is a plain substring match, deliberately
// conservative: even a comment naming it refuses. Every failure refuses the
// start rather than repair and go on: with the deny in place, a changed
// profile means something defeated it.
func checkSimulatorSandboxProfile(handoffAbs string, want []byte) error {
	dir := filepath.Join(handoffAbs, ".grok")
	path := filepath.Join(dir, "sandbox.toml")
	modified := func() error {
		return fmt.Errorf("sandbox: job profile %s was modified since Defect Drainer wrote it — refusing to start the agent", path)
	}
	if fi, err := os.Lstat(dir); err != nil || !fi.IsDir() {
		return modified()
	}
	if fi, err := os.Lstat(path); err != nil || !fi.Mode().IsRegular() {
		return modified()
	}
	got, err := os.ReadFile(path)
	if err != nil || !bytes.Equal(got, want) {
		return modified()
	}
	grokHome, err := git.GrokHome()
	if err != nil {
		return fmt.Errorf("sandbox: cannot locate the user-level sandbox.toml (%v) — refusing to start the agent", err)
	}
	user := filepath.Join(grokHome, "sandbox.toml")
	data, err := os.ReadFile(user)
	if err != nil && !os.IsNotExist(err) {
		return fmt.Errorf("sandbox: cannot read %s (%v) — refusing to start the agent", user, err)
	}
	if bytes.Contains(data, []byte(simulatorProfileName)) {
		return fmt.Errorf("sandbox: %s mentions %q, and a user-level profile of that name would replace this job's — remove it to run jobs with Simulator writes", user, simulatorProfileName)
	}
	return nil
}
