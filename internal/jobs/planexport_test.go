func TestRenderPlanExportBlockquote(t *testing.T) {
	plan := store.TestPlan{
		ID: "TPLAN-20260927-export", AppID: "app_0123456789abcdef", Key: "smoke",
		Title: "Smoke", Purpose: "why\r\nit matters", Version: 2,
		Steps: []store.PlanStep{
			{Key: "look", Position: 4, Section: "", Action: "do\r\nit", Expected: "one\ntwo\n\nthree"},
			{Key: "note", Position: 5, Section: "end", Action: "record", Expected: ""},
			{Key: "cr", Position: 6, Action: "x", Expected: "a\r\nb\rc"},
		},
	}
	got := RenderPlanExport(plan, nil, exportClock())
	if strings.Contains(got, "\r") {
		t.Fatal("CR survived")
	}
	for _, block := range []string{
		"> why\n> it matters\n",
		"### 4. `look`\n",
		"> do\n> it\n",
		"> one\n> two\n>\n> three\n",
		"> (not stated — record what you observe)\n",
		"> a\n> b\n> c\n",
	} {
		if !strings.Contains(got, block) {
			t.Fatalf("missing block %q\n%s", block, got)
		}
	}
	if strings.Contains(got, "### 4. `look` —") {
		t.Fatalf("empty section kept a suffix\n%s", got)
	}
	iLook := strings.Index(got, "### 4. `look`")
	iNote := strings.Index(got, "### 5. `note`")
	iCr := strings.Index(got, "### 6. `cr`")
	if iLook < 0 || iNote < 0 || iCr < 0 || !(iLook < iNote && iNote < iCr) {
		t.Fatalf("heading indexes look=%d note=%d cr=%d", iLook, iNote, iCr)
	}

	reordered := store.TestPlan{
		ID: "TPLAN-20260927-export", AppID: "app_0123456789abcdef", Key: "smoke",
		Title: "Smoke", Version: 1,
		Steps: []store.PlanStep{
			{Key: "later", Position: 5, Section: "s", Action: "a", Expected: "e"},
			{Key: "earlier", Position: 1, Section: "s", Action: "a", Expected: "e"},
		},
	}
	got2 := RenderPlanExport(reordered, nil, exportClock())
	i5 := strings.Index(got2, "### 5. `later`")
	i1 := strings.Index(got2, "### 1. `earlier`")
	if i5 < 0 || i1 < 0 || i5 > i1 {
		t.Fatalf("slice order: 5 at %d, 1 at %d\n%s", i5, i1, got2)
	}
}

