func TestPlanExportResultRoundTrip(t *testing.T) {
	raw := "STATUS: pass\nOpened the home screen.\n"
	status, body, ok := parseResultStatus(raw)
	if !ok || status != "pass" || body != "Opened the home screen." {
		t.Fatalf("result status %q body %q ok %v", status, body, ok)
	}
	explor := "STATUS: fail\nACTION: Tap save\nEXPECTED: Saved toast\nThe toast did not appear.\n"
	step, err := parseHarvestResult(explor, true)
	if err != "" || !step.Exploratory || step.Status != "fail" || step.Action != "Tap save" ||
		!step.HasExpected || step.Expected != "Saved toast" || step.Actual != "The toast did not appear." {
		t.Fatalf("harvest %+v err %q", step, err)
	}
}
