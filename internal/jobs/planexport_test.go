func TestPythonSplitLines(t *testing.T) {
	cases := []struct {
		in   string
		want []string
	}{
		{in: "", want: []string{}},
		{in: "a\nb", want: []string{"a", "b"}},
		{in: "a\nb\n", want: []string{"a", "b"}},
		{in: "\n", want: []string{""}},
		{in: "\n\n", want: []string{"", ""}},
		{in: "a\n\nb", want: []string{"a", "", "b"}},
		{in: "a\r\nb", want: []string{"a", "b"}},
		{in: "a\r\n", want: []string{"a"}},
		{in: "\r\n", want: []string{""}},
		{in: "a\rb", want: []string{"a", "b"}},
		{in: "a\r\n\r\nb", want: []string{"a", "", "b"}},
		{in: "a\vb", want: []string{"a", "b"}},
		{in: "a\fb", want: []string{"a", "b"}},
		{in: "a\u001cb", want: []string{"a", "b"}},
		{in: "a\u001db", want: []string{"a", "b"}},
		{in: "a\u001eb", want: []string{"a", "b"}},
		{in: "a\u0085b", want: []string{"a", "b"}},
		{in: "a\u2028b", want: []string{"a", "b"}},
		{in: "a\u2029b", want: []string{"a", "b"}},
	}
	for _, tc := range cases {
		got := pythonSplitLines(tc.in)
		if len(got) == 0 && len(tc.want) == 0 {
			continue
		}
		if strings.Join(got, "\x00") != strings.Join(tc.want, "\x00") {
			t.Fatalf("splitlines(%q) = %#v, want %#v", tc.in, got, tc.want)
		}
	}
}

