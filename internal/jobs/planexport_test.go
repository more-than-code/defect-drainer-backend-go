func assertExportLinesHeld(t *testing.T, doc string, stepCount int) {
	t.Helper()
	lines := pythonSplitLines(doc)
	contract, rules, headings, fences := 0, 0, 0, 0
	for _, line := range lines {
		switch {
		case line == "## Output contract":
			contract++
		case line == "## Rules":
			rules++
		case strings.HasPrefix(line, "### "):
			headings++
		case line == "---":
			fences++
		}
	}
	if contract != 1 || rules != 1 || headings != stepCount || fences != 2 {
		t.Fatalf("contract=%d rules=%d headings=%d fences=%d\n%s", contract, rules, headings, fences, doc)
	}
	for _, line := range stepsRegion(lines) {
		if line == "" {
			continue
		}
		if line == ">" || line == "**Action**" || line == "**Expected**" ||
			strings.HasPrefix(line, "> ") || strings.HasPrefix(line, "### ") {
			continue
		}
		t.Fatalf("disallowed steps line %q\n%s", line, doc)
	}
}

func stepsRegion(lines []string) []string {
	start := -1
	for i, line := range lines {
		if line == "## Steps" {
			start = i + 1
			break
		}
	}
	if start < 0 {
		return nil
	}
	end := len(lines)
	for i := start; i < len(lines); i++ {
		if strings.HasPrefix(lines[i], "## ") {
			end = i
			break
		}
	}
	return lines[start:end]
}

func isPyLineBreak(r rune) bool {
	switch r {
	case '\n', '\r', '\v', '\f', '\u0085', '\u2028', '\u2029', '\u001c', '\u001d', '\u001e':
		return true
	default:
		return false
	}
}

// pythonSplitLines matches Python str.splitlines() with keepends false.
func pythonSplitLines(s string) []string {
	if s == "" {
		return []string{}
	}
	var lines []string
	var b strings.Builder
	runes := []rune(s)
	for i := 0; i < len(runes); i++ {
		r := runes[i]
		if r == '\r' && i+1 < len(runes) && runes[i+1] == '\n' {
			lines = append(lines, b.String())
			b.Reset()
			i++
			continue
		}
		if isPyLineBreak(r) {
			lines = append(lines, b.String())
			b.Reset()
			continue
		}
		b.WriteRune(r)
	}
	if b.Len() > 0 {
		lines = append(lines, b.String())
	}
	return lines
}

