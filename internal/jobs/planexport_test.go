func imageExtListForTest() string {
	keys := make([]string, 0, len(imageExts))
	for k := range imageExts {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for i, k := range keys {
		keys[i] = strings.TrimPrefix(k, ".")
	}
	return strings.Join(keys, ", ")
}

func frontMatter(doc string) string {
	const open = "---\n"
	if !strings.HasPrefix(doc, open) {
		return ""
	}
	rest := doc[len(open):]
	i := strings.Index(rest, "\n---\n")
	if i < 0 {
		return ""
	}
	return rest[:i]
}

func sectionBetween(doc, start, end string) string {
	i := strings.Index(doc, start)
	if i < 0 {
		return ""
	}
	rest := doc[i+len(start):]
	j := strings.Index(rest, end)
	if j < 0 {
		return rest
	}
	return rest[:j]
}

